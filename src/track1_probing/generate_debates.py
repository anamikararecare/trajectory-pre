"""
Runs the debate loop (self-play: local model vs. itself in the opposite
role; mixed-play: local model vs. a partner backend) and, after every turn,
elicits a stance self-report from the *speaker* (paper-style questionnaire,
see src/common/questionnaire.py).

For turns generated by the local hookable model, we also cache mean-pooled
residual-stream activations at the configured layers -- this is the dataset
that src/track1_probing/probes.py trains on.

Outputs, per conversation, into `out_dir`:
  transcripts/{conv_id}.json   -- full turn-by-turn text + stance scores
  activations/{conv_id}.npz    -- {layer_idx}__{turn_idx} -> pooled vector
"""

from __future__ import annotations

import json
import os
import uuid
from typing import Optional

import numpy as np
import yaml
from tqdm import tqdm

from src.common.debate_prompts import DebateTopic, build_opening_message, build_system_prompt
from src.common.llm_client import ChatMessage, LocalHFClient, build_client, load_model_registry
from src.common.questionnaire import (
    aggregate_stance_responses,
    build_item_prompt,
    build_questionnaire_prompt,
    build_stance_items,
    parse_stance_response,
)


def _run_single_conversation(
    topic: DebateTopic,
    agent_a_client,
    agent_a_role: str,
    agent_b_client,
    agent_b_role: str,
    n_turns_per_agent: int,
    layers: list[int],
    conv_id: str,
    agent_a_model: str,
    agent_b_model: str,
    paper_compatible: bool = False,
    stance_judge_client=None,
    questionnaire_perspective: str = "subjective",
    seed: int | None = None,
) -> tuple[dict, dict]:
    """Runs one debate. agent_a is assumed to be the (or a) local hookable
    model; activations are only cached for turns agent_a generates.
    Returns (transcript_dict, activations_dict)."""

    sys_a = build_system_prompt(topic, agent_a_role, paper_compatible=paper_compatible)
    sys_b = build_system_prompt(topic, agent_b_role, paper_compatible=paper_compatible)
    opening = build_opening_message(topic, paper_compatible=paper_compatible)

    # Each agent keeps its own view of history, both starting from the
    # shared neutral opening as a "user" turn.
    history_a = [ChatMessage("system", sys_a), ChatMessage("user", opening)]
    history_b = [ChatMessage("system", sys_b), ChatMessage("user", opening)]

    turns = []
    activations = {}

    speakers = [("a", agent_a_client, agent_a_role), ("b", agent_b_client, agent_b_role)]

    if seed is not None:
        import torch

        torch.manual_seed(seed)

    for t in range(n_turns_per_agent * 2):
        who, client, role = speakers[t % 2]
        history = history_a if who == "a" else history_b

        if who == "a" and isinstance(client, LocalHFClient) and layers:
            text, acts = client.generate_with_activations(history, layers=layers)
            for layer_idx, vec in acts.items():
                activations[f"{layer_idx}__{t}"] = vec
        else:
            text = client.chat(history)

        # Questionnaire calls are separate from the visible debate history.
        item_results = []
        items = build_stance_items(topic, paper_compatible=paper_compatible)
        for item in items:
            if paper_compatible or stance_judge_client is not None:
                stance_prompt = build_item_prompt(
                    item, topic.display_name, perspective=questionnaire_perspective
                )
            else:
                stance_prompt = build_questionnaire_prompt(topic.display_name)

            judge = stance_judge_client or client
            if stance_judge_client is None:
                stance_history = history + [
                    ChatMessage("assistant", text),
                    ChatMessage("user", stance_prompt),
                ]
            else:
                visible = [
                    *(f'{turn["speaker"]}: {turn["text"]}' for turn in turns),
                    f"{who}: {text}",
                ]
                stance_history = [
                    ChatMessage(
                        "user",
                        "Conversation:\n" + "\n".join(visible) + "\n\n" + stance_prompt,
                    )
                ]
            result = {**item, "score": None, "confidence": None, "raw": None}
            stance_raw = None
            try:
                stance_raw = judge.chat(stance_history, max_tokens=180)
                stance = parse_stance_response(stance_raw)
                if not (1 <= stance.score <= 5 and 1 <= stance.confidence <= 5):
                    raise ValueError("Questionnaire values must lie on [1, 5].")
                result.update(
                    score=stance.score, confidence=stance.confidence, raw=stance.raw
                )
            except Exception as exc:  # preserve the failed raw response for audit
                result["raw"] = stance_raw
                result["error"] = repr(exc)
            item_results.append(result)

        valid_items = [item for item in item_results if item["score"] is not None]
        if len(valid_items) == len(items):
            stance_score, stance_conf = aggregate_stance_responses(valid_items)
        else:
            stance_score, stance_conf = None, None

        turns.append(
            {
                "turn": t,
                "agent_turn": t // 2 + 1,
                "speaker": who,
                "model": agent_a_model if who == "a" else agent_b_model,
                "role": role,
                "text": text,
                "stance_score": stance_score,
                "stance_confidence": stance_conf,
                "stance_responses": item_results,
            }
        )

        # update both histories with this turn as "assistant" (self) / "user" (other)
        history_a.append(ChatMessage("assistant" if who == "a" else "user", text))
        history_b.append(ChatMessage("assistant" if who == "b" else "user", text))

    transcript = {
        "conv_id": conv_id,
        "topic_id": topic.id,
        "agent_a_model": agent_a_model,
        "agent_b_model": agent_b_model,
        "agent_a_role": agent_a_role,
        "agent_b_role": agent_b_role,
        "n_turns_per_agent": n_turns_per_agent,
        "paper_compatible": paper_compatible,
        "questionnaire_perspective": questionnaire_perspective,
        "stance_judge": "external" if stance_judge_client is not None else "self",
        "local_torch_seed": seed,
        "generation": {
            "max_new_tokens": 400,
            "local_temperature": 0.8,
            "local_top_p": 0.95,
            "api_sampling": "provider_defaults; no deterministic seed",
        },
        "turns": turns,
    }
    return transcript, activations


def run_debate_set(
    topics: list[DebateTopic],
    local_model_key: str,
    partner_model_key: Optional[str],
    n_turns_per_agent: int,
    out_dir: str,
    load_in_4bit: bool = False,
    registry_path: str = "configs/models.yaml",
    paper_compatible: bool = False,
    stance_judge_model: Optional[str] = None,
    seed: int = 0,
):
    """Runs, for every topic: (1) self-play [local model vs itself, opposite
    roles], and (2) if partner_model_key given, mixed-play [local model vs
    partner, both role orders]."""

    os.makedirs(os.path.join(out_dir, "transcripts"), exist_ok=True)
    os.makedirs(os.path.join(out_dir, "activations"), exist_ok=True)

    registry = load_model_registry(registry_path)
    if registry[local_model_key]["backend"] != "hf_local":
        raise ValueError("local_model_key must identify a hookable hf_local model.")
    local_client = build_client(local_model_key, registry, load_in_4bit=load_in_4bit)
    layers = registry[local_model_key].get("default_layers", [])

    def identity(model_key: str) -> tuple:
        spec = registry[model_key]
        return spec["backend"], spec.get("hf_id") or spec.get("api_model")

    partner_client = None
    if partner_model_key and identity(partner_model_key) != identity(local_model_key):
        partner_client = build_client(
            partner_model_key,
            registry,
            load_in_4bit=load_in_4bit
            if registry[partner_model_key]["backend"] == "hf_local"
            else False,
        )

    stance_judge_client = None
    if stance_judge_model:
        if stance_judge_model == "configured":
            with open(registry_path) as registry_file:
                stance_judge_model = yaml.safe_load(registry_file)["judge_model"]
        stance_judge_client = build_client(stance_judge_model, registry)

    conditions = [
        ("self_play", local_client, local_model_key, local_client, local_model_key)
    ]
    if partner_client is not None:
        conditions.extend(
            [
                (
                    "self_play",
                    partner_client,
                    partner_model_key,
                    partner_client,
                    partner_model_key,
                ),
                (
                    "mixed_play",
                    local_client,
                    local_model_key,
                    partner_client,
                    partner_model_key,
                ),
            ]
        )

    run_index = 0
    for topic in tqdm(topics, desc="topics"):
        for condition_name, a_client, a_model_key, b_client, b_model_key in conditions:
            for role_order in [("supporter", "opposer"), ("opposer", "supporter")]:
                conv_id = f"{topic.id}__{condition_name}__{role_order[0][:3]}_{role_order[1][:3]}__{uuid.uuid4().hex[:6]}"
                transcript, activations = _run_single_conversation(
                    topic=topic,
                    agent_a_client=a_client,
                    agent_a_role=role_order[0],
                    agent_b_client=b_client,
                    agent_b_role=role_order[1],
                    n_turns_per_agent=n_turns_per_agent,
                    layers=layers if a_model_key == local_model_key else [],
                    conv_id=conv_id,
                    agent_a_model=a_model_key,
                    agent_b_model=b_model_key,
                    paper_compatible=paper_compatible,
                    stance_judge_client=stance_judge_client,
                    questionnaire_perspective="objective"
                    if stance_judge_client is not None
                    else "subjective",
                    seed=seed + run_index,
                )
                run_index += 1
                transcript["condition"] = condition_name
                transcript["model_specs"] = {
                    "agent_a": {
                        **registry[a_model_key],
                        "registry_key": a_model_key,
                        "resolved_revision": getattr(
                            getattr(a_client, "model", None), "config", None
                        )._commit_hash
                        if getattr(getattr(a_client, "model", None), "config", None)
                        and hasattr(a_client.model.config, "_commit_hash")
                        else None,
                    },
                    "agent_b": {
                        **registry[b_model_key],
                        "registry_key": b_model_key,
                        "resolved_revision": getattr(
                            getattr(b_client, "model", None), "config", None
                        )._commit_hash
                        if getattr(getattr(b_client, "model", None), "config", None)
                        and hasattr(b_client.model.config, "_commit_hash")
                        else None,
                    },
                }
                transcript["stance_judge_model"] = stance_judge_model or "self"
                with open(os.path.join(out_dir, "transcripts", f"{conv_id}.json"), "w") as f:
                    json.dump(transcript, f, indent=2)
                if activations:
                    np.savez(os.path.join(out_dir, "activations", f"{conv_id}.npz"), **activations)
